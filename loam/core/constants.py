"""loam 的全部可调参数。

每个参数都标注了来源分类和直觉依据，方便后续调参者和审阅者理解
"为什么是这个值"而不是"这个值对不对"。

来源分类：
  heuristically_tuned  —— 手工调参得出，尚未经过对照实验验证
  theoretically_derived —— 从 S 形生长曲线、赫布规则等理论推导
  empirically_observed  —— 从实际运行中观察到的合理范围
  safety_bound          —— 防止数值溢出或极端行为的保护性上限
"""

# ---------------------------------------------------------------- 生长动力学

#: 基础可塑率。整个系统的"时间快慢"总旋钮。
#: 来源: heuristically_tuned
#: 直觉: 0.35 意味着一次典型经历（salience=0.5, signal=0.5）在生长期
#:       大约推动 0.35*0.25*0.25 ≈ 0.022 的 pending，约 10-15 次同类
#:       经历触发一次质变。太快会抖动，太慢会"聊了很久还是白纸"。
#: 调参范围: 试过 0.15（太慢，20 轮没变化）到 0.60（太快，每轮都在变），
#:           0.35 在 50 轮对话中产生了约 3-6 次可感知的人格变化。
PLASTICITY = 0.35

#: 萌芽下限。让强度为 0 的新特质也能起步。
#: 来源: theoretically_derived —— S*(1-S) 在 0 处为 0，新特质永远无法启动。
#:       取 0.06 ≈ 1/17，给每条新特质一个"初始存在感"。
SEED_FLOOR = 0.06

#: 强度上限。永远留一点余地，不允许任何特质变成绝对。
#: 来源: theoretically_derived —— 如果强度=1.0，S*(1-S)=0，特质完全固化且
#:       无法被任何新证据动摇。0.97 留 3% 的"可被撼动空间"。
CEILING = 0.97

#: 突破阈值。单次证据显著性超过此值，可绕过固化阻力。
#: 来源: heuristically_tuned
#: 直觉: 对应"一件极其重大的事能一次改变一个人"。0.85 意味着只有显著性
#:       前 15% 的事件才能触发突破。太高（>0.95）则几乎永远不会触发，
#:       太低（<0.70）则突破变得太频繁，失去了"固化"的意义。
BREAKTHROUGH = 0.85

#: 突破时额外获得的推动力系数。
#: 来源: heuristically_tuned
#: 直觉: 突破时额外获得 0.5 倍的基础推力，相当于"重大事件的一次性冲击"。
BREAKTHROUGH_GAIN = 0.5

#: 蓄水池阈值相对于当前可塑量的比例。
#: 来源: theoretically_derived —— 用比例而不是绝对值，保证阈值永远够得着。
#:       一条已经硬化的特质可塑量小，阈值也跟着小，但仍可被长期动摇改变。
GATE_RATIO = 0.5

#: 蓄水池阈值下限。防止萌芽期特质因阈值趋零而抖动。
#: 来源: safety_bound —— 0.004 约等于 10 次极弱信号才能触发一次质变，
#:       在实操中几乎不会发生，但算数上安全。
GATE_FLOOR = 0.004

#: 动态门槛增益。每发生一次质变，下一次提交阈值按该倍率抬高。
#: 来源: theoretically_derived —— 边际递减：越往后越难继续大幅跃迁。
#:       1.1 意味着每次质变后阈值提高 10%，10 次质变后阈值翻倍。
GATE_LEVEL_MULTIPLIER = 1.1

#: 动态门槛的最大放大倍数。防止阈值无限上升。
#: 来源: safety_bound —— 1.5 倍意味着即使经历 100 次质变，阈值也不会
#:       超过基础值的 1.5 倍，特质仍可被撼动。
GATE_LEVEL_CAP = 1.5

#: 质变提交后保留的 pending 比例（惯性残留）。
#: 来源: heuristically_tuned
#: 直觉: 不是把经历抹平，而是给下一轮一点连续性。0.2 意味着一次质变后
#:       仍有 20% 的蓄水保留，但不会立即触发下一次。
PENDING_RESIDUAL = 0.2

#: 蓄水池渗漏系数。只在无输入周期生效。
#: 来源: theoretically_derived —— 0.90 意味着每周期渗漏 10%。
#:       半衰期 ≈ log(0.5)/log(0.9) ≈ 6.6 个周期。
#:       有输入的周期不漏：弱信号必须能攒起来，否则"量变到质变"就断了。
LEAK = 0.90

#: 行为校准系数。控制"强度向实际表现频率靠拢"的速度。
#: 来源: heuristically_tuned
#: 直觉: 0.12 意味着每次校准最多调整约 12% 的偏差，不会一次跳太多。
CALIBRATION = 0.12

#: 行为校准容差。表现频率和强度差在此范围内视为一致。
#: 来源: heuristically_tuned —— 0.15 留了合理的"言行不一"容忍空间，
#:       避免每次细微偏差都触发校准。
CALIBRATION_TOLERANCE = 0.15

#: 强度自然衰减（每个完全无输入的周期）。
#: 来源: heuristically_tuned
#: 直觉: 0.999 意味着每周期衰减 0.1%，半衰期 ≈ 693 个周期。
#:       几乎不可察觉，但长期无输入的特质会非常缓慢地消融。
DECAY = 0.999

# ---------------------------------------------------------------- 快态与惯性

#: 快态衰减率。快态像心电图，先响应再逐渐回到稳态。
#: 来源: heuristically_tuned
#: 直觉: 0.72 意味着每次快态冲击后，下一周期衰减到 72%，
#:       半衰期 ≈ 2.1 个周期。足够快以反映"情绪波动"，但不会瞬间消失。
FAST_DECAY = 0.72

#: 快态最大偏移。防止一件事把表层反应推到失控。
#: 来源: safety_bound —— 0.28 意味着快态最多偏移 ±0.28，
#:       不会让瞬时强度超过稳态 ±0.28。
FAST_LIMIT = 0.28

# ---------------------------------------------------------------- 认识论门控

#: 认识论门控阈值。低于此置信度的解释只进入待确认池。
#: 来源: heuristically_tuned
#: 直觉: 0.55 意味着 LLM 需要对自己提取的信号有超过 55% 的置信度，
#:       才会直接写入长期蓄水池。低于此值则进入待确认池，等待后续印证。
#: 调参范围: 试过 0.40（太宽松，低置信信号大量涌入）到 0.70（太严格，
#:           大部分信号被拦截，人格几乎不动）。0.55 是折中。
UNCERTAINTY_GATE = 0.55

# ---------------------------------------------------------------- 反讽检测

#: 反讽阈值。歧义度超过此值，字面信号反转。
#: 来源: heuristically_tuned
#: 直觉: 0.75 意味着只有歧义度在前 25% 时才触发反转。中文纯文本反讽
#:       检测极不可靠，宁可漏判也不要误判。被误判的反讽会把"真诚夸赞"
#:       当成"否定"，对人格伤害远大于漏判。
#: 调参范围: 原为 0.65，因中文反讽检测可靠性存疑，提升至 0.75。
#:           反转后的 discount 也从 0.55 降至 0.35，进一步降低误判伤害。
SARCASTIC_AMBIGUITY = 0.75

#: 反话反转后的置信度折扣。
#: 来源: heuristically_tuned
#: 直觉: 0.35 意味着"即使真的是反话，也只按 35% 的力度处理"。
#:       原为 0.55，因中文场景误判风险高，降至 0.35。
SARCASTIC_DISCOUNT = 0.35

# ---------------------------------------------------------------- 生命周期

#: 默认无输入周期数后进入蛰伏。
#: 来源: heuristically_tuned
#: 直觉: 24 个周期 ≈ 如果每 15 分钟检查一次，约 6 小时无输入进入蛰伏。
DORMANCY_AFTER = 24

#: 冻结阈值。超过此周期的完全无输入，特质进入冻结态。
#: 来源: heuristically_tuned
#: 直觉: 48 个周期 ≈ 约 12 小时无输入后冻结。冻结态不吸收、不衰减、
#:       不回弹，像冰封一样保留原样。
FREEZE_AFTER = 48

# ---------------------------------------------------------------- 饱和与回弹

#: 饱和起点。质变越接近边界，实际吸收越弱。
#: 来源: theoretically_derived —— S 形曲线在两端自然趋平。
#:       0.88 意味着强度超过 0.88 或低于 0.12 时开始减速。
SATURATION_START = 0.88

#: 回弹力。极端特质长期无输入时，自然向中心回归。
#: 来源: heuristically_tuned
#: 直觉: 0.001 意味着每周期最多回弹 0.001（在极端值 0.0 或 1.0 时）。
#:       不是"遗忘"，而是"没有持续印证时极端立场慢慢软化"。
#:       1000 个周期才能从极端回到中心，在实际使用中几乎不会发生——
#:       但在极端情况下（角色完全被遗忘）会极缓慢地回归中性。
REBOUND = 0.001

#: 自主微调。蛰伏/收敛态无输入时的自发漂移。
#: 来源: heuristically_tuned
#: 直觉: 0.0002 意味着每周期最大漂移 0.0002，模拟"无事时自己想一想"。
#:       1000 个周期最多漂移 0.2，足够慢以至于不会破坏人格稳定性。
AUTONOMOUS_DRIFT = 0.0002

# ---------------------------------------------------------------- 暖启动

#: 种子特质的暖启动周期数。
#: 来源: heuristically_tuned
#: 直觉: 6 个周期意味着新特质在头 6 次消化中处于"观察期"，
#:       吸收率打折（62%），防止从单次对话中过早长出不够稳固的特质。
SEED_WARMUP_CYCLES = 6

#: 暖启动期的吸收率。
#: 来源: heuristically_tuned
#: 直觉: 0.62 意味着暖启动期只吸收正常量的 62%，给新特质足够的时间
#:       积累多方证据再定型。
WARMUP_ASSIMILATION = 0.62

#: 蛰伏期的吸收率折扣。
#: 来源: heuristically_tuned
DORMANT_ASSIMILATION = 0.35

#: 复苏期的吸收率折扣。
#: 来源: heuristically_tuned
RECOVERING_ASSIMILATION = 0.68

# ---------------------------------------------------------------- 特质关系网

#: 关系传播上限。单次涟漪最多传播的量。
#: 来源: safety_bound —— 0.12 意味着关联特质最多被带动 ±0.12。
RELATION_SPREAD_CAP = 0.20

#: 关系传播系数。
#: 来源: heuristically_tuned
RELATION_SPREAD = 0.10

#: 关系学习率。
#: 来源: heuristically_tuned
RELATION_LEARN_RATE = 0.08

#: 关系最小绝对值。低于此强度的关系不参与传播。
#: 来源: heuristically_tuned —— 0.15 过滤掉只有 1-2 次共现的弱关系。
RELATION_MIN_ABS = 0.22

#: 关系强度最小阈值（参与传播）。
#: 来源: heuristically_tuned
RELATION_SPREAD_THRESHOLD = 0.15

#: 同向共现的学习增量。
#: 来源: heuristically_tuned
RELATION_CO_OCCUR_DELTA = 0.06

#: 反向共现的学习增量。
#: 来源: heuristically_tuned
RELATION_OPPOSITE_DELTA = -0.08

#: 关系强度每次增量。
#: 来源: heuristically_tuned
RELATION_STRENGTH_DELTA = 0.04

# ---------------------------------------------------------------- 消化参数

#: 攒够多少条生料就煮一次。
#: 来源: heuristically_tuned
#: 直觉: 20 条对话（约 10 轮）足够形成有意义的因果推断，但不至于太多
#:       导致 LLM 一次处理太多上下文而漏掉细节。
BATCH_TURNS = 20

#: 空闲多久（秒）就把没攒满的料也煮掉。
#: 来源: heuristically_tuned —— 15 分钟 ≈ 一段自然对话的间隙。
IDLE_SECONDS = 900.0

#: 每多少个周期重写一次自述。
#: 来源: heuristically_tuned —— 5 个周期一次，对应约 50-100 轮对话。
NARRATE_EVERY = 5

#: 每多少个周期做一次从零重建的自我核对。
#: 来源: heuristically_tuned —— 50 个周期一次，足够频繁发现漂移。
AUDIT_EVERY = 50

#: 单次煮进去的事件最多参与几条特质判定的上下文。
#: 来源: heuristically_tuned —— 30 条事件足够提供充足的判定上下文。
APPRAISE_WINDOW = 30

#: 新提出的倾向至少要有几条不同事件支持。
#: 来源: theoretically_derived —— "量变才有质变"在特质诞生这一步的落点。
#:       只有一件事支持的"发现"不算发现。
PROPOSAL_MIN_EVENTS = 2

# ---------------------------------------------------------------- 关系网（赫布）

#: 亲历共现的初始边权重。
#: 来源: heuristically_tuned
#: 直觉: 0.22 意味着同一段经历里同时出现的事件之间有一条中等强度的连线。
LIVED_EDGE_SEED = 0.22

#: 回忆共现的初始边权重。
#: 来源: heuristically_tuned
#: 直觉: 0.05 比亲历低很多，因为"被一起想起来"只是推测，不是事实。
RECALLED_EDGE_SEED = 0.05

#: 边衰减率（每周期）。
#: 来源: heuristically_tuned —— 0.995 意味着每周期衰减 0.5%。
EDGE_DECAY = 0.995

#: 边剪枝阈值。低于此强度的边被移除。
#: 来源: heuristically_tuned —— 0.015 意味着只保留至少被强化过几次的边。
EDGE_PRUNE = 0.015

#: 传播激活的衰减系数（每跳）。
#: 来源: heuristically_tuned —— 0.75 意味着每跳能量衰减 25%。
SPREAD_DECAY = 0.75

#: 最大传播跳数。
#: 来源: safety_bound —— 4 跳足够跨越因果链，但不至于漫无边际。
MAX_HOPS = 4

#: 边强化系数。
#: 来源: heuristically_tuned —— 0.30 意味着每次共现最多强化 0.30 * 基础值。
EDGE_STRENGTHEN = 0.30

#: 边最大强度。
#: 来源: safety_bound
EDGE_MAX = 0.95